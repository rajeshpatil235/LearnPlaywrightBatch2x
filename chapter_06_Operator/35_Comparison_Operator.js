//Comparison Operators

// <, >, <=, >=, ==, ===, !, !=, !==

// = //Assignment Operator
// == //Loose Comparison
// ==== //Strict Comparison

console.log(3 > 4); //false
console.log(3 < 4); //true
console.log(3 >= 4); //false //3>4 or 3===4
console.log(3 <= 4); //true //3<4 or 3===4

console.log(5 != "5");   // false
console.log(5 !== "5");  // true