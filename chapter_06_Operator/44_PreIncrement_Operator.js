//Increment
//Pre-increment operator

let a = 10;
let b = ++a;
console.log(a); //11
console.log(b); //11

//Post-increment operator
let c = 10;
let d = c++;
console.log(c); //11
console.log(d); //10

//Decrement
//Pre-decrement operator
let e = 10;
let f = --e;
console.log(e); //9
console.log(f); //9


//Post-decrement operator
let g = 10;
let h = g--;
console.log(g); //9
console.log(h); //10


