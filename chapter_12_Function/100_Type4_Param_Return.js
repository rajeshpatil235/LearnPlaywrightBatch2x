// a, b These are called parameters.
// Think of parameters as placeholders that receive values later.
// Parameter = variable in function definition
function sum(a, b) {
    return a + b;
}

// 2, 3 These are called arguments.
// They are the actual values passed when calling the function.
// Argument = actual value passed to function
let result = sum(2, 3);
console.log(result);